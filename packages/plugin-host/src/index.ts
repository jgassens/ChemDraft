function checkPageRevision(state: RequestState, document: ChemDraftDocument | undefined, pageId: string, revision: string): DocumentPage {
  const page = document?.pages.find(page => page.id === pageId);
  if (!page || state.revisions.page(page) !== revision) throw new RequestWriteError("stale", "The requested page revision is stale.");
  return page;
}

async function waitForPageChoice<T>(choice: Promise<T>, signal: AbortSignal): Promise<T | "unanswered"> {
  let cancel!: () => void;
  try {
    const unanswered = new Promise<"unanswered">(resolve => {
      cancel = () => resolve("unanswered");
      signal.addEventListener("abort", cancel, { once: true });
      if (signal.aborted) cancel();
    });
    const answer = await Promise.race([unanswered, choice]);
    return signal.aborted ? "unanswered" : answer;
  } finally { signal.removeEventListener("abort", cancel); }
}

