/** The legacy selection's page binding (Send time). Ids on `pageId` bind to it; see pinSelectionPages. */
export function legacyWriteScopePages(document: ChemDraftDocument | undefined, objectIds: readonly string[],
  pageId = document?.selection.pageId ?? document?.pages[0]?.id): Map<string, string> | undefined {
  if (!document?.pages.some(page => page.id === pageId)) return undefined;
  return pinSelectionPages(document, objectIds, pageId).pages;
}

/** `scopePages` must already be rebound to `document` with effectiveScopePages. */
function assertLegacyWriteTargetPage(document: ChemDraftDocument, scopePages: PluginWriteScopePages | undefined,
  op: ReturnType<typeof writePatchOps>[number]): void {
  if (!scopePages?.size || op.op === "addObject" || op.op === "addAnnotation") return;
  const ids = op.op === "setObjectOrder" ? op.objectIds : "objectId" in op ? [op.objectId] : [];
  for (const id of ids) {
    const pinned = scopePages.get(id);
    if (pinned === undefined) continue;
    const target = op.op === "setObjectOrder" ? op.pageId : bareIdTargetPage(document, id);
    if (target === undefined || target === pinned) continue;
    if (!resolveObjectOnPage(document, pinned, id)) {
      throw new PluginHostError(duplicateIdRefusalMessage(document, id, pinned,
        objectLocations(document, id).map(location => location.page.id), false));
    }
    throw new PluginHostError(duplicateIdRefusalMessage(document, id, pinned, [target]));
  }
}

/** Refuse a legacy write whose page-bound target id would resolve to a same-id object on another page.
 * A uniquely identified object that moved pages since Send is followed, not refused. */
export function assertLegacyWritePages(document: ChemDraftDocument, patch: DocumentPatch,
  scopePages: PluginWriteScopePages | undefined): void {
  const pins = effectiveScopePages(document, scopePages);
  for (const op of writePatchOps(patch)) assertLegacyWriteTargetPage(document, pins, op);
}

/** Host-only preflight. Embedders must rerun against the document they will actually commit after
 * any gesture wait. Keep the authored patch so rebasing uses commit-time ids, not preflight ids. */
export function assertPluginPatchWriteScope(
  document: ChemDraftDocument,
  proposed: NormalizedProposedDocumentPatch,
  objectIds: readonly string[],
  preflight = rebasePluginPatch(document, proposed),
  beforeObjectWrite?: ApplyPatchOptions["beforeObjectWrite"],
  /** Legacy writes only: bind selected ids to their selection page. */
  scopePages?: PluginWriteScopePages
): ChemDraftDocument {
  // Follow a uniquely identified object that moved pages; never a same-id object on another page.
  scopePages = effectiveScopePages(document, scopePages);
  const scope = new Set(objectIds);
  for (const op of writePatchOps(preflight.patch)) {
    assertLegacyWriteTargetPage(document, scopePages, op);
    if (op.op === "addObject") scope.add(op.object.id);
    else if (op.op === "addAnnotation") scope.add(op.annotation.id);
    else {
      const ids = op.op === "setObjectOrder" ? op.objectIds : "objectId" in op ? [op.objectId] : [];
      for (const id of ids) {
        if (!scope.has(id)) throw new PluginHostError(`${id} was not selected when the command started`);
      }
    }
  }
  // Inspect one atomic draft, without normalizing partial pairs or forward references between ops.
  const validated = applyPatch(document, preflight.patch, { beforeObjectWrite, preserveRepeatUnitBrackets: true, deferGroupCleanup: true, beforeRemoveObjects: (draft, objectIds) => {
    const removed = new Set(objectIds);
    for (const page of draft.pages) {
      for (const object of page.objects) {
        if (object.type === "reaction" && !removed.has(object.id) && !objectInWriteScope(scope, scopePages, page.id, object.id)
          && !sameDocumentValue(pruneReactionObjectReferences(object, removed), object)
          && page.objects.some(candidate => removed.has(candidate.id))) {
          const id = objectIds.find(id => page.objects.some(candidate => candidate.id === id) &&
            !sameDocumentValue(pruneReactionObjectReferences(object, new Set([id])), object));
          if (id === undefined) continue;
          throw new PluginHostError(
            `Plugin patch refused: removing ${id} would change reaction ${object.id}, which this command may not modify.`
          );
        }
      }
    }
  } });
  // Reserve reference-identical survivors first. For cloned/revalidated objects, match each id's
  // remaining occurrences in document order; a last-wins map conflates valid duplicate ids.
  const originals = document.pages.flatMap(page => page.objects.map(object => ({ page, object })));
  const survivors = validated.pages.flatMap(page => page.objects);
  const remainingReferences = new Map<DocumentObject, number>();
  for (const object of survivors) remainingReferences.set(object, (remainingReferences.get(object) ?? 0) + 1);
  const matchedReferences = new Map<DocumentObject, number>();
  const unmatched = originals.filter(({ object }) => {
    const count = remainingReferences.get(object) ?? 0;
    if (!count) return true;
    remainingReferences.set(object, count - 1);
    matchedReferences.set(object, (matchedReferences.get(object) ?? 0) + 1);
    return false;
  });
  const remainingById = new Map<string, DocumentObject[]>();
  for (const object of survivors) {
    const matched = matchedReferences.get(object) ?? 0;
    if (matched) {
      matchedReferences.set(object, matched - 1);
      continue;
    }
    const occurrences = remainingById.get(object.id) ?? [];
    occurrences.push(object);
    remainingById.set(object.id, occurrences);
  }
  const occurrences = new Map<string, number>();
  for (const { page, object } of unmatched) {
    const index = occurrences.get(object.id) ?? 0;
    occurrences.set(object.id, index + 1);
    const survivor = remainingById.get(object.id)?.[index];
    if (objectInWriteScope(scope, scopePages, page.id, object.id) ||
      (survivor && sameDocumentValue(authoredObjectValue(object), authoredObjectValue(survivor)))) continue;
    if (object.type === "bracket") {
      const removal = writePatchOps(preflight.patch).find(op => op.op === "removeObject" &&
        page.objects.some(candidate => candidate.id === op.objectId) &&
        (object.containedObjectIds.includes(op.objectId) || object.crossingBondIds?.some(ref => ref.objectId === op.objectId)));
      if (removal?.op === "removeObject") {
        throw new PluginHostError(`Removing "${removal.objectId}" would change bracket "${object.id}", which is not selected`);
      }
    }
    throw new PluginHostError(`Patch would change object "${object.id}", which is not selected`);
  }
  assertPluginPageWriteScope(document, validated, scope, scopePages);
  return validated;
}

export interface ScopedRepeatUnitCleanup {
  readonly commandStartDocument: ChemDraftDocument;
  authoredRemovals: ReadonlyMap<string, ReadonlySet<string>>;
}

export function beginScopedRepeatUnitCleanup(document: ChemDraftDocument | undefined): ScopedRepeatUnitCleanup | undefined {
  return document && { commandStartDocument: document, authoredRemovals: new Map() };
}

/** Prepare only after scope accepts the authored document. Record deletions once history commits,
 * so a later write can orphan a populated unit by deleting its last temporary member. */
export function finishScopedRepeatUnitCleanup(cleanup: ScopedRepeatUnitCleanup | undefined,
  before: ChemDraftDocument, authored: ChemDraftDocument, patch: DocumentPatch) {
  const removed = new Set(writePatchOps(patch).flatMap(op => op.op === "removeObject" ? [op.objectId] : []));
  if (!removed.size) return undefined;
  const authoredRemovals = new Map(cleanup?.authoredRemovals);
  const currentRemovals = new Map<string, Set<string>>();
  for (const page of before.pages) {
    const next = authored.pages.find(candidate => candidate.id === page.id);
    if (!next) continue;
    const surviving = new Set(next.objects.map(object => object.id));
    const ids = page.objects.flatMap(object => removed.has(object.id) && !surviving.has(object.id) ? [object.id] : []);
    if (!ids.length) continue;
    currentRemovals.set(page.id, new Set(ids));
    authoredRemovals.set(page.id, new Set([...(authoredRemovals.get(page.id) ?? []), ...ids]));
  }
  if (!currentRemovals.size) return undefined;
  const deletedMember = (unit: OrphanedRepeatUnit, deletions: ReadonlyMap<string, ReadonlySet<string>>) =>
    [...unit.deletedMoleculeIds].some(id => deletions.get(unit.pageId)?.has(id));
  const options = { wholeMoleculesOnly: true };
  let liveOrphans: OrphanedRepeatUnit[] | undefined;
  const orphaned = cleanup ? planOrphanedRepeatUnitCleanup(cleanup.commandStartDocument, authored, options).filter(unit => {
    if (deletedMember(unit, currentRemovals)) return true;
    if (!deletedMember(unit, cleanup.authoredRemovals)) return false;
    liveOrphans ??= planOrphanedRepeatUnitCleanup(before, authored, options).filter(candidate => deletedMember(candidate, currentRemovals));
    return liveOrphans.some(candidate => candidate.pageId === unit.pageId &&
      unit.bracketIds.every(id => candidate.bracketIds.includes(id)));
  }) : [];
  return {
    document: removeOrphanedRepeatUnitBrackets(authored, orphaned, currentRemovals),
    record: () => { if (cleanup) cleanup.authoredRemovals = authoredRemovals; }
  };
}

/** Last check at the history boundary, AFTER all normalization and placement. Only rebased patch
 * insertions whose ids did not exist in `before` extend scope; neither receipts nor derived additions
 * grant access to existing objects. Unlike preflight, every final object field is compared. */
export function assertPluginDocumentWriteScope(
  before: ChemDraftDocument,
  after: ChemDraftDocument,
  proposed: NormalizedProposedDocumentPatch,
  objectIds: readonly string[],
  /** Legacy writes only: a granted id is exempt only on the page its selection named. */
  scopePages?: PluginWriteScopePages
): void {
  scopePages = effectiveScopePages(before, scopePages);
  const originals = before.pages.flatMap(page => page.objects.map(object => ({ pageId: page.id, object })));
  const survivors = after.pages.flatMap(page => page.objects.map(object => ({ pageId: page.id, object })));
  const existingIds = new Set(originals.map(entry => entry.object.id));
  const inserted = new Set(writePatchOps(rebasePluginPatch(before, proposed).patch).flatMap(op =>
    op.op === "addObject" ? [op.object.id] : op.op === "addAnnotation" ? [op.annotation.id] : []
  ).filter(id => !existingIds.has(id)));
  const scope = new Set(objectIds);
  type Entry = typeof survivors[number];
  // Reserve reference-identical occurrences before matching cloned occurrences by id, so a duplicate
  // id cannot hide an edit or removal of its earlier occurrence (including on another page).
  const byReference = new Map<DocumentObject, Entry[]>();
  for (const entry of survivors) {
    const entries = byReference.get(entry.object) ?? [];
    entries.push(entry);
    byReference.set(entry.object, entries);
  }
  const matches = new Map<typeof originals[number], Entry>();
  const matched = new Set<Entry>();
  for (const original of originals) {
    const entries = byReference.get(original.object);
    if (!entries?.length) continue;
    const samePage = entries.findIndex(entry => entry.pageId === original.pageId);
    const [entry] = entries.splice(samePage < 0 ? 0 : samePage, 1);
    matches.set(original, entry!);
    matched.add(entry!);
  }
  const byId = new Map<string, Entry[]>();
  for (const entry of survivors) {
    if (matched.has(entry)) continue;
    const entries = byId.get(entry.object.id) ?? [];
    entries.push(entry);
    byId.set(entry.object.id, entries);
  }
  for (const original of originals) {
    const survivor = matches.get(original) ?? byId.get(original.object.id)?.shift();
    if (survivor) matched.add(survivor);
    if (objectInWriteScope(scope, scopePages, original.pageId, original.object.id)) continue;
    if (survivor?.pageId === original.pageId && sameDocumentValue(original.object, survivor.object)) continue;
    const detail = !survivor ? "removed" : survivor.pageId !== original.pageId ? "moved to another page"
      : pluginObjectChangeDescription(original.object, survivor.object);
    throw new PluginHostError(`Plugin write refused: ${original.object.type} "${original.object.id}" was ${detail}, but was not selected when the command started.`);
  }
  for (const entry of survivors) {
    if (!matched.has(entry) && !inserted.has(entry.object.id)) {
      throw new PluginHostError(`Plugin write refused: ${entry.object.type} "${entry.object.id}" was added outside this command's insertions.`);
    }
  }
  assertPluginPageWriteScope(before, after, new Set([...scope, ...inserted]), scopePages);
}

function pluginObjectChangeDescription(before: DocumentObject, after: DocumentObject): string {
  if (before.type === "molecule" && after.type === "molecule") {
    for (const atom of before.atoms) {
      const next = after.atoms.find(candidate => candidate.id === atom.id);
      if (!next) return `changed by removing atom "${atom.id}"`;
      if (sameDocumentValue(atom, next)) continue;
      const fields = Object.keys({ ...atom, ...next }).filter(key =>
        !sameDocumentValue(atom[key as keyof typeof atom], next[key as keyof typeof next]));
      const names: Record<string, string> = { formalCharge: "formal charge", markCharge: "mark charge",
        markRadicals: "mark radicals", labelBondSide: "label bond side" };
      return `changed at atom "${atom.id}" (${fields.map(key => names[key] ?? key).join(", ")})`;
    }
  }
  const fields = Object.keys({ ...before, ...after }).filter(key =>
    !sameDocumentValue((before as Record<string, unknown>)[key], (after as Record<string, unknown>)[key]));
  return `changed (${fields.join(", ")})`;
}

