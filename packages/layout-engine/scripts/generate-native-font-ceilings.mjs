// Offline only. Read the licensed fonts on the author's machine, emit advance numbers,
// never font outlines or binaries. Usage: node <this script> /System/Library/Fonts
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export function readFaces(path) {
  const data = readFileSync(path);
  const offsets = data.toString("ascii", 0, 4) === "ttcf"
    ? Array.from({ length: data.readUInt32BE(8) }, (_, i) => data.readUInt32BE(12 + i * 4)) : [0];
  return offsets.map(offset => {
    const tables = {};
    for (let i = 0; i < data.readUInt16BE(offset + 4); i++) {
      const record = offset + 12 + i * 16;
      tables[data.toString("ascii", record, record + 4)] = data.readUInt32BE(record + 8);
    }
    const units = data.readUInt16BE(tables.head + 18);
    const count = data.readUInt16BE(tables.hhea + 34);
    const advances = Array.from({ length: count }, (_, i) => data.readUInt16BE(tables.hmtx + i * 4) / units);
    // OpenType name ID 6 is the PostScript face name; TTC order is not a contract.
    const names = [];
    for (let i = 0; i < data.readUInt16BE(tables.name + 2); i++) {
      const record = tables.name + 6 + i * 12;
      if (data.readUInt16BE(record + 6) !== 6) continue;
      const start = tables.name + data.readUInt16BE(tables.name + 4) + data.readUInt16BE(record + 10);
      const bytes = data.subarray(start, start + data.readUInt16BE(record + 8));
      names.push([0, 3].includes(data.readUInt16BE(record))
        ? Array.from({ length: bytes.length / 2 }, (_, j) => String.fromCharCode(bytes.readUInt16BE(j * 2))).join("")
        : bytes.toString("ascii"));
    }
    let cmap;
    for (let i = 0; i < data.readUInt16BE(tables.cmap + 2); i++) {
      const record = tables.cmap + 4 + i * 8;
      const subtable = tables.cmap + data.readUInt32BE(record + 4);
      if ([0, 3].includes(data.readUInt16BE(record)) && data.readUInt16BE(subtable) === 4) cmap = subtable;
    }
    if (cmap === undefined) throw new Error(`No Unicode format-4 cmap in ${path}`);
    return {
      names,
      revision: data.readUInt32BE(tables.head + 4) / 65536,
      max: Math.max(...advances),
      advance(codePoint) {
        const segments = data.readUInt16BE(cmap + 6) / 2;
        const ends = cmap + 14, starts = ends + 2 * segments + 2;
        const deltas = starts + 2 * segments, ranges = deltas + 2 * segments;
        for (let i = 0; i < segments; i++) {
          if (codePoint > data.readUInt16BE(ends + i * 2)) continue;
          if (codePoint < data.readUInt16BE(starts + i * 2)) return undefined;
          const range = data.readUInt16BE(ranges + i * 2);
          let glyph = range ? data.readUInt16BE(ranges + i * 2 + range
            + 2 * (codePoint - data.readUInt16BE(starts + i * 2))) : codePoint;
          if (range && glyph === 0) return undefined;
          glyph = (glyph + data.readInt16BE(deltas + i * 2)) & 65535;
          return glyph === 0 ? undefined : advances[Math.min(glyph, count - 1)];
        }
        return undefined;
      }
    };
  });
}

export function namedFace(path, name) {
  const faces = readFaces(path).filter(face => face.names.includes(name));
  if (faces.length !== 1) throw new Error(`Expected exactly one ${name} face in ${path}, found ${faces.length}`);
  return faces[0];
}

export function core14CodePoints(afm) {
  return [...new Set(Object.values(afm).flatMap(values => Object.keys(values).map(Number)))].sort((a, b) => a - b);
}

function generateNativeFontCeilings(directory) {
  if (!directory) throw new Error("Supply the source font directory (see README.md)");
  const afmSource = readFileSync(new URL("../src/textMetrics.generated.ts", import.meta.url), "utf8");
  const afm = Object.fromEntries([...afmSource.matchAll(/export const (\w+):[^=]+= (\{[\s\S]*?\});/g)]
    .map(match => [match[1], JSON.parse(match[2])]));
  // Union all seven AFM maps, including glyphs absent from Helvetica's map.
  const codePoints = core14CodePoints(afm);
  const chemistryCharacters = "⇌⇄→←↔≡≈±×·′″°⁺⁻⁰¹²³⁴⁵⁶⁷⁸⁹₀₁₂₃₄₅₆₇₈₉αβγδεζηθικλμνξοπρςστυφχψωΑΒΓΔΕΖΗΘΙΚΛΜΝΞΟΠΡΣΤΥΦΧΨΩµÅ‰";
  const ceilEm = value => Math.ceil(value * 1000) / 1000;
  const chemistry = Array.from({ length: 4 }, () => ({}));
  let output = "// Generated by scripts/generate-native-font-ceilings.mjs; sources and scope: README.md.\n"
    + "// Face order: regular, bold, italic, bold italic. Only upward corrections to Core14.\n";
  for (const [family, core, collection, postscriptNames, collectionNames] of [
    ["Arial", "helvetica", "Helvetica", ["ArialMT", "Arial-BoldMT", "Arial-ItalicMT", "Arial-BoldItalicMT"],
      ["Helvetica", "Helvetica-Bold", "Helvetica-Oblique", "Helvetica-BoldOblique"]],
    ["Times New Roman", "times", "Times", ["TimesNewRomanPSMT", "TimesNewRomanPS-BoldMT", "TimesNewRomanPS-ItalicMT", "TimesNewRomanPS-BoldItalicMT"],
      ["Times-Roman", "Times-Bold", "Times-Italic", "Times-BoldItalic"]],
    ["Courier New", "courier", "Courier", ["CourierNewPSMT", "CourierNewPS-BoldMT", "CourierNewPS-ItalicMT", "CourierNewPS-BoldItalicMT"],
      ["Courier", "Courier-Bold", "Courier-Oblique", "Courier-BoldOblique"]],
    ["Georgia", "times", undefined, ["Georgia", "Georgia-Bold", "Georgia-Italic", "Georgia-BoldItalic"], []]
  ]) {
    const nativeFaces = collection ? collectionNames.map(name => namedFace(join(directory, `${collection}.ttc`), name)) : [];
    const corrections = ["", " Bold", " Italic", " Bold Italic"].map((suffix, index) => {
      const face = namedFace(join(directory, "Supplemental", `${family}${suffix}.ttf`), postscriptNames[index]);
      const base = afm[`${core}${["Advances", "BoldAdvances", "ItalicAdvances", "BoldItalicAdvances"][index]}`]
        ?? afm[`${core}${index % 2 ? "BoldAdvances" : "Advances"}`] ?? afm.courierAdvances;
      console.log(`${family}${suffix}: revision=${face.revision}, H=${face.advance(72)}, max=${face.max}`);
      for (const character of chemistryCharacters) {
        const cp = character.codePointAt(0);
        const width = Math.max(base[cp] ?? 0, face.advance(cp) ?? 0, nativeFaces[index]?.advance(cp) ?? 0);
        if (width > 0) chemistry[index][cp] = Math.max(chemistry[index][cp] ?? 0, ceilEm(width));
      }
      return Object.fromEntries(codePoints.flatMap(cp => {
        const width = Math.max(face.advance(cp) ?? 0, nativeFaces[index]?.advance(cp) ?? 0);
        return width > (base[cp] ?? 0) ? [[cp, ceilEm(width)]] : [];
      }));
    });
    output += `\nexport const ${family.split(" ")[0].toLowerCase()}AdvanceCeilings: readonly Readonly<Record<number, number>>[] = [\n`
      + corrections.map(values => `  ${JSON.stringify(values)}`).join(",\n") + "\n];\n";
  }
  for (const [index, values] of chemistry.entries()) {
    for (const character of chemistryCharacters) {
      if (values[character.codePointAt(0)] === undefined) {
        console.warn(`No source advance for ${character} (style ${index}); using uncovered-character policy, 1 em`);
      }
    }
  }
  output += "\n// Chemistry/typography fallback: maximum across all seven real families and Core14, per style.\n"
    + "// Omitted characters have no source glyph and use the 1 em uncovered policy (see generator diagnostics).\n"
    + `export const chemistryAdvanceCeilings: readonly Readonly<Record<number, number>>[] = [\n`
    + chemistry.map(values => `  ${JSON.stringify(values)}`).join(",\n") + "\n];\n";
  writeFileSync(new URL("../src/nativeFontCeilings.generated.ts", import.meta.url), output);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateNativeFontCeilings(process.argv[2]);
}
