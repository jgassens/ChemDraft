// Run from any directory: node packages/export-engine/scripts/generate-font-coverage.mjs
// No font payload is needed at runtime to choose a family/style.
import { readFileSync, writeFileSync } from "node:fs";

const families = {
  ChemDraftNotoSans: ["NotoSans-Regular", "NotoSans-Bold", "NotoSans-Italic", "NotoSans-BoldItalic"],
  ChemDraftDejaVuSans: ["DejaVuSans", "DejaVuSans-Bold", "DejaVuSans-Oblique", "DejaVuSans-BoldOblique"]
};
const faces = ["normal", "bold", "italic", "bolditalic"];

function coverage(bytes) {
  for (let i = 0; i < bytes.readUInt16BE(4); i++) {
    const record = 12 + i * 16;
    if (bytes.toString("ascii", record, record + 4) !== "cmap") continue;
    const cmap = bytes.subarray(bytes.readUInt32BE(record + 8));
    for (let j = 0; j < cmap.readUInt16BE(2); j++) {
      const encoding = 4 + j * 8;
      if (cmap.readUInt16BE(encoding) !== 3 || cmap.readUInt16BE(encoding + 2) !== 1) continue;
      const table = cmap.subarray(cmap.readUInt32BE(encoding + 4));
      if (table.readUInt16BE(0) !== 4) continue;
      const count = table.readUInt16BE(6) / 2;
      const starts = 16 + count * 2;
      const deltas = starts + count * 2;
      const offsets = deltas + count * 2;
      const codes = new Set();
      for (let segment = 0; segment < count; segment++) {
        const end = table.readUInt16BE(14 + segment * 2);
        const start = table.readUInt16BE(starts + segment * 2);
        const delta = table.readInt16BE(deltas + segment * 2);
        const address = offsets + segment * 2;
        const offset = table.readUInt16BE(address);
        for (let code = start; code <= end; code++) {
          const glyph = offset ? table.readUInt16BE(address + offset + 2 * (code - start)) : code;
          if ((!offset || glyph) && ((glyph + delta) & 0xffff)) codes.add(code);
        }
      }
      const ranges = [];
      for (const code of [...codes].sort((a, b) => a - b)) {
        if (ranges.length && ranges.at(-1) + 1 === code) ranges[ranges.length - 1] = code;
        else ranges.push(code, code);
      }
      return ranges;
    }
  }
  throw new Error("Font has no Windows Unicode BMP cmap");
}

const unique = new Map();
const entries = [];
for (const [family, files] of Object.entries(families)) {
  const faceEntries = files.map((file, index) => {
    const source = readFileSync(new URL(`../src/fonts/${file}.ts`, import.meta.url), "utf8");
    const payload = source.match(/export default "([A-Za-z0-9+/=]+)";/)?.[1];
    if (!payload) throw new Error(`Missing base64 payload in ${file}`);
    const ranges = coverage(Buffer.from(payload, "base64"));
    const key = JSON.stringify(ranges);
    if (!unique.has(key)) unique.set(key, { name: `ranges${unique.size}`, ranges });
    return `    ${faces[index]}: ${unique.get(key).name}`;
  });
  entries.push(`  ${family}: {\n${faceEntries.join(",\n")}\n  }`);
}
const definitions = [...unique.values()].map(({ name, ranges }) => {
  const lines = [];
  for (let i = 0; i < ranges.length; i += 16) lines.push(`  ${ranges.slice(i, i + 16).join(", ")}`);
  return `const ${name}: readonly number[] = [\n${lines.join(",\n")}\n];`;
});
writeFileSync(new URL("../src/fonts/coverage.ts", import.meta.url),
  `// Generated by packages/export-engine/scripts/generate-font-coverage.mjs. Do not edit.\n` +
  `// Inclusive BMP code-point pairs with nonzero glyph IDs; identical faces share ranges.\n` +
  `${definitions.join("\n\n")}\n\nexport const fontCoverage = {\n${entries.join(",\n")}\n};\n`);
