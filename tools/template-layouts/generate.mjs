import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");

export function renderFamily(generator) {
  const entries = generator.generateTemplates();
  const data = entries.length ? JSON.stringify(entries, null, 2) : "[]";
  return `// Generated by tools/template-layouts/${generator.scriptName}, do not edit by hand.\n` +
    `import type { StructureTemplate } from "./types";\n\n` +
    `export const ${generator.exportName}: readonly StructureTemplate[] = ${data};\n`;
}

export function writeFamily(generator, check = false) {
  const target = path.join(repositoryRoot, "packages", "template-library", "src", "structureTemplates", generator.fileName);
  const expected = renderFamily(generator);
  if (check) {
    let actual;
    try { actual = readFileSync(target, "utf8"); }
    catch (error) { if (error.code !== "ENOENT") throw error; }
    // Checkouts may use CRLF on Windows; generated content is otherwise byte-for-byte stable.
    if (actual?.replace(/\r\n/g, "\n") !== expected) {
      console.error(`Stale structure template file: ${path.relative(repositoryRoot, target)}`);
      return false;
    }
  } else {
    writeFileSync(target, expected, "utf8");
  }
  return true;
}

/** Each family script can also regenerate/check just its own file, from any working directory. */
export function runFamilyIfMain(moduleUrl, generator) {
  if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(moduleUrl)) {
    if (!writeFamily(generator, process.argv.includes("--check"))) process.exitCode = 1;
  }
}
