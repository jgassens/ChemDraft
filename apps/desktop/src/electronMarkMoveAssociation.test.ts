const normalizeDocumentEdit = (before: ChemDraftDocument, patched: ChemDraftDocument) => {
  const document = normalizeCommittedDocument(patched);
  return { document, chemistryChanges: electronMarkChemistryChanges(before, document) };
};

const fixture = (spec: workflow.NativeElectronMarkSpec) => associationFixture(workflow, spec);
afterEach(() => vi.unstubAllGlobals());
beforeAll(() => installRealRdkitModuleLoader());
afterAll(() => resetRdkitForTesting());

describe.each([false, true])("main's mark association policy with direct editing %s", enabled => {
  beforeEach(() => {
    vi.stubGlobal("localStorage", new MemoryStorage());
    saveDirectElectronMarkEditing(enabled);
  });

  // Fixed expectations regenerated by RUNNING these SAME operations with the merged workflow
  // and HEAD^1 ba6e141247fc433c439ef694a5c9a58fcd1199f7's normal commit reconciliation policy.
  // d6d16b2546cca26c584c126be2eced5be186d2e5: "Charge and radical reconciliation keeps a charge on
  // the atom the user clicked." Valence warnings must never reassign duplicated radical ions.
  // The fixture captures raw anchors separately and checks every atom's charge/radical fields.
  it.each(specs)("matches main's stored anchors and resulting chemistry for %j", spec => {
    for (const { name, before, patched } of mainAssociationCases(workflow, spec)) {
      const beforeJson = JSON.stringify(before), patchedJson = JSON.stringify(patched);
      const result = normalizeDocumentEdit(before, patched);
      const expected = (mainOracle.cases as Record<string, unknown>)[`${JSON.stringify(spec)}: ${name}`];
      expect(expected, name).toBeDefined();
      if (["alignment", "crowded alignment", "crowded multi molecule group alignment"].includes(name)) {
        // Ordinary marks keep their anchors whenever carried with the molecule, selected or not.
        const state = associationState(patched, result.document);
        const original = associationState(before, before);
        expect(state.stored, name).toEqual(original.stored);
        expect(state.committed, name).toEqual(original.committed);
        expect(result.chemistryChanges, name).toEqual([]);
        for (const molecule of moleculesIn(result.document)) {
          const old = moleculesIn(before).find(object => object.id === molecule.id)!;
          expect(molecule.bonds, name).toEqual(old.bonds);
          expect(molecule.chemistry, name).toEqual(old.chemistry);
          molecule.atoms.forEach((atom, index) => {
            expect({ ...atom, x: old.atoms[index].x, y: old.atoms[index].y }, name).toEqual(old.atoms[index]);
          });
        }
        // Keep the pinned movement oracle: only association and resulting chemistry change.
        const positions = (state: ReturnType<typeof associationState>) => state.molecules.map(([id, atoms]) =>
          [id, (atoms as { x: number; y: number }[]).map(({ x, y }) => ({ x, y }))]);
        expect(positions(state), name).toEqual(positions(expected as ReturnType<typeof associationState>));
      } else if (["duplicate small offset", "duplicate large offset", "paste"].includes(name)) {
        // A copied pair belongs to the copied molecule, even near the original.
        // Keep the old position oracle, but independently check the corrected association and chemistry.
        const original = fixture(spec).molecule;
        const copied = moleculesIn(result.document).find(o => !moleculesIn(before).some(old => old.id === o.id))!;
        for (const old of before.pages[0].objects) expect(result.document.pages[0].objects.find(o => o.id === old.id), name).toEqual(old);
        copied.atoms.forEach((atom, index) => expect({ ...atom, x: original.atoms[index].x, y: original.atoms[index].y }, name).toEqual(original.atoms[index]));
        expect(copied.chemistry, name).toEqual(original.chemistry);
        expect(copied.structure, name).toEqual(original.structure);
        for (const state of [patched, result.document]) {
          const mark = state.pages[0].objects.find(o => o.type === "electron-mark" && !before.pages[0].objects.some(old => old.id === o.id))!;
          expect(mark, name).toMatchObject({ anchor: { kind: "atom", objectId: copied.id, atomId: original.atoms[0].id } });
        }
        const positions = (state: ReturnType<typeof associationState>) => state.molecules.map(([id, atoms]) =>
          [id, (atoms as { x: number; y: number }[]).map(({ x, y }) => ({ x, y }))]);
        expect(positions(associationState(patched, result.document)), name).toEqual(positions(expected as ReturnType<typeof associationState>));
      } else expect(associationState(patched, result.document), name).toEqual(expected);
      expect(result.chemistryChanges).toEqual(electronMarkChemistryChanges(before, result.document));
      expect(JSON.stringify(before)).toBe(beforeJson);
      expect(JSON.stringify(patched)).toBe(patchedJson);
    }
  });

  it.each(specs)("reports actual release/transfer and unchanged chemistry for %j", spec => {
    const cases = mainAssociationCases(workflow, spec);
    const { mark, molecule } = fixture(spec);
    const original = molecule.atoms[0];
    const charge = spec.kind === "charge" ? spec.charge : 0;
    const radicals = spec.kind === "radical-dot" || (spec.kind === "charge" && spec.radical) ? 1 : 0;
    for (const { name, before, patched } of cases.filter(c => !c.name.includes("duplicate") && !c.name.includes("paste"))) {
      const { document, chemistryChanges } = normalizeDocumentEdit(before, patched);
      const finalMark = markIn(document);
      const oldMark = markIn(before);
      const transferred = finalMark.anchor.kind === "atom" && (finalMark.anchor.objectId !== oldMark.anchor.objectId ||
        finalMark.anchor.atomId !== oldMark.anchor.atomId);
      const released = finalMark.anchor.kind !== "atom";
      // Main's fixed association expectations above independently pin which endpoints it chooses.
      expect(chemistryChanges, name).toEqual(spec.kind === "lone-pair" || (!released && !transferred) ? [] : [{
        markId: mark.id, objectIdBefore: oldMark.anchor.objectId, atomIdBefore: original.id,
        objectIdAfter: released ? undefined : finalMark.anchor.objectId,
        atomIdAfter: released ? undefined : finalMark.anchor.atomId,
        chargeDelta: released && charge ? -charge : 0, radicalDelta: released && radicals ? -radicals : 0
      }]);
    }
  });

  it.each(specs)("reports exactly main's chemistry differences for copied %j", spec => {
    const chargeDelta = spec.kind === "charge" ? spec.charge : 0;
    const radicalDelta = spec.kind === "radical-dot" || (spec.kind === "charge" && spec.radical) ? 1 : 0;
    const prefix = spec.kind === "charge" ? "charge" : "electron";
    const added = (markId: string, objectIdAfter: string, atomIdAfter = "atom_001") => ({
      markId, objectIdBefore: undefined, atomIdBefore: undefined, objectIdAfter, atomIdAfter, chargeDelta, radicalDelta
    });
    const existing = { ...added("charge_003", "mol_bond_001"),
      objectIdBefore: "mol_bond_001", atomIdBefore: "atom_001" };
    // Co-selected pairs copy their chemistry to the copied molecule. Mark-only duplication
    // retains its existing policy, including the original-atom radical contribution.
    const expected = {
      "duplicate small offset": [added(`${prefix}_copy_005`, "mol_copy_004")],
      "duplicate large offset": [added(`${prefix}_copy_005`, "mol_copy_004")],
      "duplicate mark only": [existing, added(`${prefix}_copy_004`, "mol_bond_001")],
      "paste": [added(`${prefix}_copy_001`, "mol_copy_002")],
      "stale paste missing atom": [added(`${prefix}_copy_001`, "mol_copy_002", "atom_002")],
      "stale paste missing molecule": []
    };
    for (const [name, changes] of Object.entries(expected)) {
      const { before, patched } = mainAssociationCases(workflow, spec).find(c => c.name === name)!;
      expect(normalizeDocumentEdit(before, patched).chemistryChanges, name).toEqual(spec.kind === "lone-pair" ? [] : changes);
    }
  });

  it.each(specs)("keeps main's stale point anchors for floating moves of %j", spec => {
    const { document, mark } = fixture(spec);
    const floating = { ...mark, anchor: { kind: "point" as const, point: { x: 600, y: 600 } }, x: 591, y: 591 };
    expect(electronMarkMoveAssociation(document, floating, { x: 600, y: 600 }, { x: 620, y: 620 })).toEqual({
      anchor: spec.kind === "charge" ? { kind: "point", point: { x: 620, y: 620 } } : floating.anchor
    });
  });
});

it("compares atom chemistry even when the mark's association is unchanged", () => {
  const { document, mark, molecule } = fixture({ kind: "charge", charge: 1 });
  const changed: ChemDraftDocument = { ...document, pages: [{ ...document.pages[0], objects:
    document.pages[0].objects.map(o => o.id === molecule.id && o.type === "molecule" ? { ...o,
      atoms: o.atoms.map((atom, index) => index ? atom : { ...atom, formalCharge: atom.formalCharge + 1 }) } : o) }] };
  expect(electronMarkChemistryChanges(document, changed)).toEqual([{
    markId: mark.id, objectIdBefore: molecule.id, atomIdBefore: molecule.atoms[0].id,
    objectIdAfter: molecule.id, atomIdAfter: molecule.atoms[0].id, chargeDelta: 1, radicalDelta: 0
  }]);
  const provenanceOnly: ChemDraftDocument = { ...document, pages: [{ ...document.pages[0], objects:
    document.pages[0].objects.map(o => o.id === molecule.id && o.type === "molecule" ? { ...o,
      atoms: o.atoms.map((atom, index) => index ? atom : { ...atom, markCharge: 2 }) } : o) }] };
  expect(electronMarkChemistryChanges(document, provenanceOnly)).toEqual([{
    markId: mark.id, objectIdBefore: molecule.id, atomIdBefore: molecule.atoms[0].id,
    objectIdAfter: molecule.id, atomIdAfter: molecule.atoms[0].id, chargeDelta: 0, radicalDelta: 0
  }]);
  const radicalsOnly = structuredClone(document);
  moleculesIn(radicalsOnly)[0].atoms[0].markRadicals = 1;
  markIn(radicalsOnly).radical = true;
  expect(electronMarkChemistryChanges(document, radicalsOnly)).toEqual([{
    markId: mark.id, objectIdBefore: molecule.id, atomIdBefore: molecule.atoms[0].id,
    objectIdAfter: molecule.id, atomIdAfter: molecule.atoms[0].id, chargeDelta: 0, radicalDelta: 1
  }]);
  expect(electronMarkChemistryChanges(document, structuredClone(document))).toEqual([]);
});

it("uses the real multi-molecule reconciled result, even for equal local atom ids", () => {
  const { document, mark, molecule } = associationFixture(workflow, { kind: "charge", charge: 1 }, true);
  const target = moleculesIn(document)[1];
  expect(mark.anchor).toEqual({ kind: "atom", objectId: molecule.id, atomId: molecule.atoms[0].id });
  const patched = workflow.moveDocumentObjects(document, [molecule.id, target.id, mark.id], 80, 100);
  expect(markIn(patched).anchor).toEqual({ ...mark.anchor, kind: "point", point: {
    x: nativeChargeMarkCenter(mark).x + 80, y: nativeChargeMarkCenter(mark).y + 100
  } });
  expect(normalizeDocumentEdit(document, patched).chemistryChanges).toEqual([{
    markId: mark.id, objectIdBefore: molecule.id, atomIdBefore: molecule.atoms[0].id,
    objectIdAfter: target.id, atomIdAfter: target.atoms[0].id, chargeDelta: 0, radicalDelta: 0
  }]);
});

it.each(specs)("keeps canonical SMILES, formula, charge, radicals and anchors during appearance edits of %j", async spec => {
  const { document, mark } = fixture(spec);
  const before = moleculesIn(document);
  expect(before[0].chemistry?.formula).toBeTruthy();
  expect(before[0].structure).toBeTruthy();
  const module = await ensureRdkit();
  const originalIdentity = inspectStructureInWorker(module, stereoPerceptionMolfile(before[0]));
  expect(originalIdentity.valid).toBe(true);
  if (!originalIdentity.valid) throw new Error(originalIdentity.reason);
  expect(originalIdentity.canonicalSmiles).toBeTruthy();
  expect(originalIdentity.formula).toBeTruthy();
  let edited = applyElectronMarkStyleToSelection(document, "size", 72);
  edited = applyElectronMarkStyleToSelection(edited, "thickness", 5.5);
  edited = scaleDocumentObjectsAroundPoint(edited, [mark.id], nativeChargeMarkCenter(markIn(edited)), 1.25, 1.25);
  edited = rotateDocumentObject(edited, mark.id, 73);
  edited = normalizeCommittedDocument(edited);
  expect(moleculesIn(edited)).toEqual(before);
  expect(inspectStructureInWorker(module, stereoPerceptionMolfile(moleculesIn(edited)[0]))).toEqual(originalIdentity);
  expect(markIn(edited).anchor).toEqual(mark.anchor);
});
