import { existsSync, readFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { expect, it } from "vitest";

const readNative = (path: string) => readFileSync(fileURLToPath(new URL(`../src-tauri/${path}`, import.meta.url)), "utf8");

it("removes the unguarded palette focus command from registration, capabilities, permissions and wrapper", () => {
  const command = ["set", "toolset", "window", "focusable"].join("_");
  for (const file of ["build.rs", "src/lib.rs"]) expect(readNative(file)).not.toContain(command);
  for (const file of readdirSync(fileURLToPath(new URL("../src-tauri/capabilities/", import.meta.url)))) {
    expect(readNative(`capabilities/${file}`)).not.toContain(command.replaceAll("_", "-"));
  }
  expect(existsSync(fileURLToPath(new URL(`../src-tauri/permissions/autogenerated/${command}.toml`, import.meta.url)))).toBe(false);
  expect(readFileSync(fileURLToPath(new URL("./window-manager/index.ts", import.meta.url)), "utf8")).not.toContain(command);
  expect(readFileSync(fileURLToPath(new URL("./perf/commandSignatures.json", import.meta.url)), "utf8")).not.toContain(command);
});

it("grants toolset windows exactly the two authenticated input lease commands on both platforms", () => {
  const capability = JSON.parse(readNative("capabilities/toolset-input-focus.json"));
  expect(capability.windows).toEqual(["toolset-*"]);
  expect(capability.platforms).toBeUndefined();
  expect(capability.permissions).toEqual([
    "allow-register-plugin-panel-input-focus", "allow-set-plugin-panel-input-focus"
  ]);
  for (const command of ["register_plugin_panel_input_focus", "set_plugin_panel_input_focus"]) {
    const permission = readNative(`permissions/autogenerated/${command}.toml`);
    expect(permission).toContain(`identifier = "allow-${command.replaceAll("_", "-")}"`);
    expect(permission).toContain(`commands.allow = ["${command}"]`);
  }
});

it("installs native focus observation for palettes and popovers and resets per-window leases on page load", () => {
  const source = readNative("src/lib.rs");
  for (const name of ["ensure_toolset_window", "build_toolset_popover_window"]) {
    const build = source.split(`fn ${name}`)[1]!.split("\nfn ")[0]!;
    expect(build).toContain("install_toolset_input_focus(&window)?");
  }
  const pageLoad = source.split(".on_page_load(")[1]!.split(".on_menu_event(")[0]!;
  expect(pageLoad).toContain("is_input_focus_window_label(webview.label())");
  expect(pageLoad).toContain("PageLoadEvent::Started");
  expect(pageLoad).toContain("panel_window::reset_for_webview(&webview.window())");
  const panel = readNative("src/panel_window.rs");
  expect(panel).toContain("Some(focus_subclass)");
  expect(panel).toContain('"chemdraft://plugin-panel-focus"');
  expect(panel).toContain("window.emit_to(window.label()");
});
